CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    senha VARCHAR(100) NOT NULL,
    papel VARCHAR(20) NOT NULL CHECK (papel IN ('CIDADAO', 'GESTOR'))
);
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao VARCHAR(300) NOT NULL
);
CREATE TABLE solicitacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    endereco VARCHAR(250) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('ABERTA', 'EM_ATENDIMENTO', 'RESOLVIDA', 'CANCELADA')),
    prioridade VARCHAR(10) NOT NULL CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    cidadao_id BIGINT NOT NULL REFERENCES usuarios(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_solicitacoes_cidadao ON solicitacoes(cidadao_id);
CREATE INDEX ix_solicitacoes_status ON solicitacoes(status);
CREATE INDEX ix_solicitacoes_categoria ON solicitacoes(categoria_id);
